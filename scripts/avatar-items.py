"""Avatar item layers (docs/vuma/avatar-items-art.md).

  python scripts/avatar-items.py cut <item> <grok-edit.png> [--from N] [--stage N] [--box x0,y0,x1,y1]
      Cut the item out of a Grok edit of public/vuma/hero-NN.jpg (--from, default 9) by
      comparing it with that picture, and save it as a transparent layer:
      public/vuma/items/<item>.png (all stages) or <item>-NN.png with --stage.
      A PNG that already has transparency is used as it is (only resized to 600x540).
  python scripts/avatar-items.py manifest
      Rewrite lib/avatar/art.generated.mjs from the files in public/vuma/items/ (cut does this too).
  python scripts/avatar-items.py preview [--out file.jpg]
      All 19 hero pictures wearing every item that has a layer, plus the round crops, to check the fit.

An item is sold in the Coin Shop only once a layer covers every stage.
"""
import argparse, hashlib, json, os, re, sys, tempfile
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VUMA = os.path.join(ROOT, 'public', 'vuma')
ITEMS_DIR = os.path.join(VUMA, 'items')
MANIFEST = os.path.join(ROOT, 'lib', 'avatar', 'art.generated.mjs')
STAGES = 19
W, H = 600, 540
HEAD_CROP = (185, 80, 185 + 230, 80 + 230)  # = HEAD_CROP in lib/avatar/items.mjs
ORDER = ['tv', 'tshirt', 'hoodie', 'cap', 'football']  # back to front, = AVATAR_ITEMS
# Where each item may be (the player stands at the same spot in every hero picture);
# changes outside the box are ignored. Override with --box.
BOXES = {
    'cap': (180, 60, 420, 250),
    'tshirt': (180, 190, 420, 410),
    'hoodie': (170, 140, 430, 430),
    'football': (140, 190, 460, 440),
    'tv': (0, 0, W, H),
}
THRESHOLD = 48       # per-channel difference that counts as "changed"
MAX_COVER = 0.45     # more changed than this = the edit moved the whole picture


def hero(n):
    return Image.open(os.path.join(VUMA, f'hero-{n:02d}.jpg')).convert('RGB')


def cut(item, src, base_stage, stage, box):
    if item not in ORDER:
        sys.exit(f'unknown item {item!r}; one of {", ".join(ORDER)}')
    im = Image.open(src)
    os.makedirs(ITEMS_DIR, exist_ok=True)
    out = os.path.join(ITEMS_DIR, f'{item}-{stage:02d}.png' if stage else f'{item}.png')
    if im.mode in ('RGBA', 'LA', 'P') and im.convert('RGBA').getextrema()[3][0] < 255:
        im.convert('RGBA').resize((W, H), Image.NEAREST).save(out)
        print('saved (already transparent)', out)
        return
    edit = im.convert('RGB').resize((W, H), Image.LANCZOS)
    base = hero(base_stage)
    diff = ImageChops.difference(edit, base).split()
    d = ImageChops.lighter(ImageChops.lighter(diff[0], diff[1]), diff[2])
    mask = d.point(lambda v: 255 if v > THRESHOLD else 0)
    keep = Image.new('L', (W, H), 0)
    ImageDraw.Draw(keep).rectangle(box, fill=255)
    mask = ImageChops.multiply(mask, keep)
    # drop speckles, close small gaps
    mask = mask.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(3))
    # fill holes (parts of the item that happen to match the original kit)
    corner = next((pt for pt in ((0, 0), (W - 1, 0), (0, H - 1), (W - 1, H - 1)) if mask.getpixel(pt) == 0), None)
    if corner:
        filled = mask.copy()
        ImageDraw.floodfill(filled, corner, 128)
        mask = filled.point(lambda v: 0 if v == 128 else 255)
    cover = sum(mask.histogram()[1:]) / (W * H)
    if cover == 0:
        sys.exit('nothing changed inside the box: wrong --from picture or --box?')
    if cover > MAX_COVER:
        sys.exit(f'{cover:.0%} of the picture changed: the edit moved or restyled the whole picture. '
                 'Ask Grok to keep everything else identical, or supply a transparent PNG.')
    layer = edit.convert('RGBA')
    layer.putalpha(mask)
    layer.save(out)
    print(f'saved {out} ({cover:.1%} of the frame)')


def manifest():
    art = {}
    names = sorted(os.listdir(ITEMS_DIR)) if os.path.isdir(ITEMS_DIR) else []
    for name in names:
        m = re.fullmatch(r'([a-z]+)(?:-(\d\d))?\.png', name)
        if not m or m.group(1) not in ORDER:
            continue
        a = art.setdefault(m.group(1), {'shared': False, 'stages': [], 'h': hashlib.sha1()})
        if m.group(2):
            a['stages'].append(int(m.group(2)))
        else:
            a['shared'] = True
        with open(os.path.join(ITEMS_DIR, name), 'rb') as f:
            a['h'].update(name.encode() + f.read())
    out = {k: {'shared': a['shared'], 'stages': sorted(a['stages']), 'v': a['h'].hexdigest()[:8]} for k, a in sorted(art.items())}
    with open(MANIFEST, 'w', newline='\n', encoding='utf-8') as f:
        f.write('// GENERATED by scripts/avatar-items.py (npm run avatar:items) — do not edit.\n')
        f.write('// Which avatar item layers exist in public/vuma/items/:\n')
        f.write('//   { <id>: { shared: bool, stages: [stage numbers], v: cache key } }\n')
        f.write(f'export const ITEM_ART = {json.dumps(out, indent=2)};\n')
    print('manifest:', ', '.join(f"{k} ({'all' if v['shared'] else len(v['stages'])})" for k, v in out.items()) or 'no layers yet')


def layer_for(item, n):
    for name in (f'{item}-{n:02d}.png', f'{item}.png'):
        p = os.path.join(ITEMS_DIR, name)
        if os.path.exists(p):
            return Image.open(p).convert('RGBA').resize((W, H), Image.NEAREST)
    return None


def preview(out):
    tw, th, cs = 300, 270, 120
    sheet = Image.new('RGB', (5 * (tw + cs), 4 * th), (20, 8, 40))
    for i in range(STAGES):
        n = i + 1
        pic = hero(n).convert('RGBA')
        for item in ORDER:
            lay = layer_for(item, n)
            if lay:
                pic = Image.alpha_composite(pic, lay)
        x, y = (i % 5) * (tw + cs), (i // 5) * th
        sheet.paste(pic.convert('RGB').resize((tw, th)), (x, y))
        sheet.paste(pic.crop(HEAD_CROP).convert('RGB').resize((cs, cs)), (x + tw, y))
    sheet.save(out, quality=90)
    print('preview:', out)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='cmd', required=True)
    c = sub.add_parser('cut')
    c.add_argument('item')
    c.add_argument('src')
    c.add_argument('--from', dest='base', type=int, default=9)
    c.add_argument('--stage', type=int, default=0)
    c.add_argument('--box')
    sub.add_parser('manifest')
    v = sub.add_parser('preview')
    v.add_argument('--out', default=os.path.join(tempfile.gettempdir(), 'avatar-items-preview.jpg'))
    a = p.parse_args()
    if a.cmd == 'cut':
        if a.stage and not 1 <= a.stage <= STAGES:
            sys.exit(f'--stage must be 1..{STAGES}')
        box = tuple(int(x) for x in a.box.split(',')) if a.box else BOXES.get(a.item, (0, 0, W, H))
        cut(a.item, a.src, a.base, a.stage, box)
        manifest()
    elif a.cmd == 'manifest':
        manifest()
    else:
        preview(a.out)


if __name__ == '__main__':
    main()
